import assert from "node:assert/strict"
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { withTestTsgo } from "../tsgo-test-executable.ts"
import {
  type CompilerApi,
  contains,
  expectNoQueryWrites,
  fixture,
  lacks,
  type Suite,
  tsgoNoEmit,
} from "./support.ts"

/**
 * Standard Schema interop, against the real checker: zod, valibot and arktype schemas are
 * resolved from the fixture (no fixture node_modules, no tsconfig paths entry), discovered
 * next to tskm schemas, and emitted as sidecars the checker accepts.
 */
export function standardSuites(api: CompilerApi): Suite[] {
  const fixtureRoot = fixture("standard")
  const fx = (rel: string) => fixture(`standard/src/${rel}`)

  const generateGuarded = (root: string, config: Parameters<CompilerApi["generate"]>[0]) =>
    expectNoQueryWrites(root, () => api.generate(config))

  const removeAll = (files: ReadonlyArray<string>) => () => {
    for (const f of files) {
      if (existsSync(f)) rmSync(f)
    }
  }

  // ---- resolution smoke ----------------------------------------------------------------
  const sidecar = fx("zod-basic.schema.gen.ts")
  const queryFile = fx("zod-basic.schema.tskm-query.ts")
  const resolution: Suite = {
    title: "standard schema interop (real tsgo) — resolution smoke",
    teardown: removeAll([sidecar, queryFile]),
    scenarios: [
      {
        name: "resolves a zod schema to a fully-expanded sidecar type",
        timeout: 60_000,
        run: async () => {
          const result = await generateGuarded(fixtureRoot, {
            root: fixtureRoot,
            config: withTestTsgo({
              mode: "sidecar",
              include: ["src/zod-basic.schema.ts"],
              tsconfig: "tsconfig.json",
            }),
          })

          assert.equal(result.files.length, 1)
          assert.deepEqual(result.files[0]?.typeNames, ["Account"])

          const gen = readFileSync(sidecar, "utf8")
          contains(gen, "export type Account = {")
          contains(gen, "id: string")
          // zod's optional() marks the KEY optional (unlike tskm's value-union form)
          contains(gen, "age?: number | undefined")
          contains(gen, "roles: string[]")
          contains(gen, "bio: string | null")
          // transform's POST-transform output type
          contains(gen, "nameLength: number")
        },
      },
      {
        name: "silently drops a guarded candidate that is not a schema",
        run: () => {
          // `parsedValue` (a z.string().parse(...) call) was a syntactic candidate;
          // the emitted sidecar must not contain it, and no diagnostic refers to it.
          const gen = readFileSync(sidecar, "utf8")
          lacks(gen, "ParsedValue")
          lacks(gen, "NotASchema")
        },
      },
      {
        name: "emits a sidecar the real tsgo accepts (emit-ability, separate from resolution)",
        timeout: 120_000,
        run: () => {
          const check = tsgoNoEmit(api, fixtureRoot)
          lacks(check.output, "error TS")
          assert.equal(check.ok, true)
        },
      },
      {
        name: "leaves no query files behind",
        run: () => {
          assert.equal(existsSync(queryFile), false)
        },
      },
    ],
  }

  // ---- post-resolution compile gate ----------------------------------------------------
  const leakSidecar = fx("zod-leak.schema.gen.ts")
  const leakVerify = fx("zod-leak.schema.verify.tskm-query.ts")
  const compileGate: Suite = {
    title: "standard schema interop (real tsgo) — post-resolution compile gate",
    teardown: removeAll([leakSidecar, leakVerify]),
    scenarios: [
      {
        name: "refuses to write a sidecar whose rendered type cannot compile, preserving the old output",
        timeout: 60_000,
        run: async () => {
          // Pre-seed a known-good previous sidecar: the gate must leave it untouched.
          const previous =
            "// AUTO-GENERATED by tskm. Do not edit.\n\nexport type Weird = { ok: true }\n"
          writeFileSync(leakSidecar, previous)

          const result = await generateGuarded(fixtureRoot, {
            root: fixtureRoot,
            config: withTestTsgo({
              mode: "sidecar",
              include: ["src/zod-leak.schema.ts"],
              tsconfig: "tsconfig.json",
            }),
          })

          // (iii) diagnostics: the gate names the failure, the unresolved identifier
          // (extracted from the checker's message text), and the fail-closed outcome
          contains(result.diagnostics.join("\n"), "do not compile")
          contains(result.diagnostics.join("\n"), "unresolved name(s): LocalThing")
          contains(result.diagnostics.join("\n"), "Existing output left untouched")
          // (i) resolution outcome: no file emitted for this source
          assert.deepEqual(result.files, [])
          // (ii) emit-ability outcome: the previous sidecar is byte-identical
          assert.equal(readFileSync(leakSidecar, "utf8"), previous)
          // and the verify probe never survives
          assert.equal(existsSync(leakVerify), false)
        },
      },
    ],
  }

  // ---- per-library scenarios -----------------------------------------------------------
  const gen = (include: string) =>
    generateGuarded(fixtureRoot, {
      root: fixtureRoot,
      config: withTestTsgo({ mode: "sidecar", include: [include], tsconfig: "tsconfig.json" }),
    })

  const perLibrary: Suite = {
    title: "standard schema interop (real tsgo) — per-library scenarios",
    teardown: removeAll([
      fx("valibot.schema.gen.ts"),
      fx("arktype.schema.gen.ts"),
      fx("zod-brand.schema.gen.ts"),
      fx("zod-recursive.schema.gen.ts"),
      fx("zod-recursive-alias.schema.gen.ts"),
      fx("zod-recursive-local.schema.gen.ts"),
      fx("mixed.schema.gen.ts"),
      fx("probe.check.ts"),
    ]),
    scenarios: [
      {
        name: "valibot: basic + pipe transform + GenericSchema recursion + brand",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/valibot.schema.ts")
          // (i) resolution
          assert.deepEqual(result.files[0]?.typeNames, ["User", "Node", "Uid"])
          const out = readFileSync(fx("valibot.schema.gen.ts"), "utf8")
          contains(out, "age?: number | undefined")
          contains(out, "score: number") // post-transform output
          // the annotated root renders as the named reference itself — semantically
          // exact: the user's interface IS the type
          contains(out, "export type Node = VNode")
          contains(out, 'import type { VNode } from "./valibot.schema"')
          contains(out, 'import type { Brand } from "valibot"')
          contains(out, 'Brand<"Uid">')
        },
      },
      {
        name: "arktype: basic object",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/arktype.schema.ts")
          assert.deepEqual(result.files[0]?.typeNames, ["User"])
          const out = readFileSync(fx("arktype.schema.gen.ts"), "utf8")
          contains(out, "name: string")
          contains(out, "age?: number | undefined")
        },
      },
      {
        name: "zod: brand emits the $brand import and stays nominal (probe)",
        timeout: 120_000,
        run: async () => {
          const result = await gen("src/zod-brand.schema.ts")
          assert.deepEqual(result.files[0]?.typeNames, ["UserId", "Card"])
          const out = readFileSync(fx("zod-brand.schema.gen.ts"), "utf8")
          // (i) resolution: raw rendering for the top-level brand, no prototype explosion
          contains(out, 'export type UserId = string & $brand<"UserId">')
          contains(out, 'import type { $brand } from "zod"')
          lacks(out, "toUpperCase") // no String prototype leak

          // (ii) emit-ability + nominal semantics, asserted at the value level
          writeFileSync(
            fx("probe.check.ts"),
            [
              'import type { UserId } from "./zod-brand.schema.gen.ts"',
              "declare const id: UserId",
              "const base: string = id",
              "// @ts-expect-error a plain string must not be assignable to the branded type",
              'const nominal: UserId = "plain"',
              "export const ok = [base, nominal]",
              "",
            ].join("\n"),
          )
          const check = tsgoNoEmit(api, fixtureRoot)
          lacks(check.output, "error TS")
          assert.equal(check.ok, true)
        },
      },
      {
        name: "zod: exported self-annotation recursion imports the annotation type",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/zod-recursive.schema.ts")
          assert.deepEqual(result.files[0]?.typeNames, ["Cat"])
          const out = readFileSync(fx("zod-recursive.schema.gen.ts"), "utf8")
          contains(out, 'import type { CatT } from "./zod-recursive.schema"')
          contains(out, "CatT")
        },
      },
      {
        name: "zod: an ALIASED exported self-annotation imports the type rebound to its rendered name",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/zod-recursive-alias.schema.ts")
          // (i) resolution: the schema resolves and the file passes the compile gate
          // (a written sidecar IS the gate's emit-ability verdict)
          assert.deepEqual(result.diagnostics, [])
          assert.deepEqual(result.files[0]?.typeNames, ["AliasCat"])
          const out = readFileSync(fx("zod-recursive-alias.schema.gen.ts"), "utf8")
          contains(
            out,
            'import type { PublicCatT as AliasCatT } from "./zod-recursive-alias.schema"',
          )
          contains(out, "AliasCatT")
        },
      },
      {
        name: "zod: a LOCAL self-annotation is skipped with the export-it diagnostic, leaking nothing",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/zod-recursive-local.schema.ts")
          // (iii) diagnostics name the fix
          contains(result.diagnostics.join("\n"), "export type CatLocalT = ...")
          // (i) nothing resolved for this file
          assert.deepEqual(result.files, [])
          // (ii) no sidecar with a bare un-importable name
          assert.equal(existsSync(fx("zod-recursive-local.schema.gen.ts")), false)
        },
      },
      {
        name: "mixed file: tskm and zod schemas land in ONE sidecar",
        timeout: 60_000,
        run: async () => {
          const result = await gen("src/mixed.schema.ts")
          assert.deepEqual(result.files[0]?.typeNames, ["Core", "Zod"])
          const out = readFileSync(fx("mixed.schema.gen.ts"), "utf8")
          contains(out, "export type Core = {")
          contains(out, "id: string")
          contains(out, "export type Zod = {")
          contains(out, "label: string")
        },
      },
      {
        name: "opt-out (schemaSources: []) discovers no external schemas",
        timeout: 60_000,
        run: async () => {
          const result = await generateGuarded(fixtureRoot, {
            root: fixtureRoot,
            config: withTestTsgo({
              mode: "sidecar",
              include: ["src/zod-basic.schema.ts"],
              tsconfig: "tsconfig.json",
              schemaSources: [],
            }),
          })
          assert.deepEqual(result.files, [])
        },
      },
      {
        name: "regenerating produces byte-identical output (idempotency — the watch-loop guard)",
        timeout: 60_000,
        run: async () => {
          await gen("src/mixed.schema.ts")
          const first = readFileSync(fx("mixed.schema.gen.ts"), "utf8")
          await gen("src/mixed.schema.ts")
          assert.equal(readFileSync(fx("mixed.schema.gen.ts"), "utf8"), first)
        },
      },
    ],
  }

  // ---- annotation-free recursion boundary pin ------------------------------------------
  const badRoot = fixture("standard-bad")
  const badSidecar = fixture("standard-bad/src/zod-getter.schema.gen.ts")
  const boundary: Suite = {
    title: "standard schema interop (real tsgo) — annotation-free recursion boundary pin",
    teardown: removeAll([badSidecar]),
    scenarios: [
      {
        // Pins the spike-verified behavior: zod itself self-truncates annotation-free
        // recursion (never TS2589), so the emitted type carries `any` at the cut —
        // FAITHFUL to what z.infer shows in the user's editor. A future regression to
        // a hard failure (or to silent full-`any`) breaks this pin. Full fidelity
        // requires the library-idiomatic self annotation (README known limits).
        name: "emits the degraded (self-truncated) type zod infers, without failing",
        timeout: 60_000,
        run: async () => {
          const result = await generateGuarded(badRoot, {
            root: badRoot,
            config: withTestTsgo({
              mode: "sidecar",
              include: ["src/*.schema.ts"],
              tsconfig: "tsconfig.json",
            }),
          })
          assert.equal(result.files.length, 1)
          assert.deepEqual(result.diagnostics, [])
          const out = readFileSync(badSidecar, "utf8")
          contains(out, "export type Cat = {")
          contains(out, "kitten: any")
        },
      },
    ],
  }

  // ---- inplace gating ------------------------------------------------------------------
  const inplaceSource = fx("inplace-ext.ts")
  const inplaceGating: Suite = {
    title: "standard schema interop — inplace gating",
    teardown: removeAll([inplaceSource]),
    scenarios: [
      {
        name: "an external alias in inplace mode is skipped with an explicit unsupported diagnostic",
        timeout: 60_000,
        run: async () => {
          const source = [
            'import { z } from "zod"',
            "const cfgSchema = z.object({ debug: z.boolean() })",
            "export type Cfg = Infer<typeof cfgSchema>",
            "",
          ].join("\n")
          writeFileSync(inplaceSource, source)

          const result = await generateGuarded(fixtureRoot, {
            root: fixtureRoot,
            config: withTestTsgo({
              mode: "inplace",
              include: ["src/inplace-ext.ts"],
              tsconfig: "tsconfig.json",
            }),
          })

          // (iii) explicit diagnostic, never silent staleness
          const text = result.diagnostics.join("\n")
          contains(text, "inplace mode supports only tskm schemas")
          contains(text, "zod")
          // (i)/(ii) the source is untouched
          assert.deepEqual(result.files, [])
          assert.equal(readFileSync(inplaceSource, "utf8"), source)
        },
      },
    ],
  }

  return [resolution, compileGate, perLibrary, boundary, inplaceGating]
}
